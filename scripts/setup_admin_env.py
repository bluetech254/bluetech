#!/usr/bin/env python3
"""
scripts/setup_admin_env.py — Write admin environment variables on cPanel.

Run this in the cPanel "Setup Python App" terminal tab:

    python3 setup_admin_env.py

What it does:
  - Writes a .env file that GitHub Actions reads during the Next.js build
  - The NEXT_PUBLIC_* vars get baked into the static output at build time
  - No Node.js or npm required — this only creates/updates the .env file

After running:
  - Trigger a redeploy (push a commit, or re-run the GitHub Actions workflow)
  - The new build will use these values
"""

import os
import sys

SEP = "=" * 60

def ok(msg, detail=""):
    print(f"  ✓  {msg}" + (f"  —  {detail}" if detail else ""))

def fail(msg, detail=""):
    print(f"  ✗  {msg}" + (f"  —  {detail}" if detail else ""))
    sys.exit(1)

def section(title):
    print(f"\n{SEP}\n  {title}\n{SEP}")


# ── Detect admin directory ─────────────────────────────────────────────────────

section("1. Locating admin directory")

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT  = os.path.dirname(SCRIPT_DIR)

# Try common cPanel paths
CANDIDATES = [
    os.path.join(REPO_ROOT, "admin"),                    # repo/admin/
    "/home2/fixitblu/bluetech/admin",
    "/home/fixitblu/bluetech/admin",
    os.path.join(os.path.expanduser("~"), "bluetech", "admin"),
]

ADMIN_DIR = None
for path in CANDIDATES:
    if os.path.isdir(path) and os.path.exists(os.path.join(path, "package.json")):
        ADMIN_DIR = path
        break

if not ADMIN_DIR:
    fail(
        "Could not find admin directory",
        f"Looked in: {', '.join(CANDIDATES)}"
    )

ok("Found admin directory", ADMIN_DIR)
ENV_FILE = os.path.join(ADMIN_DIR, ".env")


# ── Write .env ────────────────────────────────────────────────────────────────

section("2. Writing admin/.env")

ENV_CONTENT = """\
# =============================================================================
# admin/.env  — auto-generated by scripts/setup_admin_env.py
# DO NOT commit this file to git.
# Re-run this script to regenerate after any value changes.
# =============================================================================

# ── API ───────────────────────────────────────────────────────────────────────
# Production backend URL — no trailing slash
NEXT_PUBLIC_API_URL=https://api.fixit-bluetechnology.co.ke

# ── Business Info ─────────────────────────────────────────────────────────────
NEXT_PUBLIC_BUSINESS_NAME=Fixit Blue Technology
NEXT_PUBLIC_BUSINESS_ADDRESS=Nairobi CBD
NEXT_PUBLIC_BUSINESS_EMAIL=info@fixit-bluetechnology.co.ke
NEXT_PUBLIC_BUSINESS_PHONE=+254 707 454182
NEXT_PUBLIC_BUSINESS_TAGLINE=Your trusted repair & tech partner — fast, honest, professional.
"""

with open(ENV_FILE, "w", encoding="utf-8") as f:
    f.write(ENV_CONTENT)

# Restrict permissions so only the app user can read it
try:
    os.chmod(ENV_FILE, 0o600)
    ok("Permissions set to 600 (owner read/write only)")
except Exception:
    pass

ok("admin/.env written", ENV_FILE)


# ── Print what was written ────────────────────────────────────────────────────

section("3. Verification — values written")

print()
for line in ENV_CONTENT.strip().splitlines():
    if line and not line.startswith("#") and "=" in line:
        key, _, val = line.partition("=")
        print(f"    {key.strip():<40} = {val.strip()}")
print()


# ── Done ──────────────────────────────────────────────────────────────────────

print(f"""
{SEP}
  ✓  Done.

  The admin .env has been written with production values.

  IMPORTANT — Next step:
  ──────────────────────
  These NEXT_PUBLIC_* variables are baked into the Next.js
  build at compile time. To apply them you must trigger a
  new build by either:

    Option A (recommended):
      Push any commit to the 'production' branch — GitHub
      Actions will rebuild and deploy automatically.

    Option B (manual):
      In cPanel File Manager, confirm admin/.env exists at:
        {ENV_FILE}
      Then re-run your GitHub Actions deploy workflow.

{SEP}
""")
