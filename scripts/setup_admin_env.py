#!/usr/bin/env python3
"""
scripts/setup_admin_env.py — Admin panel environment setup for cPanel.

Run this on the cPanel server to write the admin .env file and
optionally trigger a rebuild of the Next.js static export.

Usage:
    cd /home2/fixitblu/admin
    python3 ../scripts/setup_admin_env.py

What it does:
  1. Writes admin/.env with all NEXT_PUBLIC_* variables
  2. Optionally rebuilds the Next.js app (npm run build)
  3. Copies the built /out directory to the public_html folder

Safe to re-run — overwrites .env each time with the correct values.
"""

import os
import subprocess
import sys
import shutil

# ── Paths ─────────────────────────────────────────────────────────────────────

SCRIPT_DIR  = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT   = os.path.dirname(SCRIPT_DIR)
ADMIN_DIR   = os.path.join(REPO_ROOT, "admin")
ENV_FILE    = os.path.join(ADMIN_DIR, ".env")


def section(title: str) -> None:
    print(f"\n{'=' * 60}\n  {title}\n{'=' * 60}")


def ok(label: str, detail: str = "") -> None:
    print(f"  ✓  {label}" + (f"  —  {detail}" if detail else ""))


def fail(label: str, detail: str = "") -> None:
    print(f"  ✗  {label}" + (f"  —  {detail}" if detail else ""))


# ── Step 1: Write admin/.env ──────────────────────────────────────────────────

section("1. Writing admin/.env")

ENV_CONTENT = """\
# =============================================================================
# admin/.env  — auto-generated by scripts/setup_admin_env.py
# DO NOT commit this file to git.
# Re-run setup_admin_env.py to regenerate after any changes.
# =============================================================================

# ── API ───────────────────────────────────────────────────────────────────────
NEXT_PUBLIC_API_URL=https://api.fixit-bluetechnology.co.ke

# ── Business Info ─────────────────────────────────────────────────────────────
NEXT_PUBLIC_BUSINESS_NAME=Fixit Blue Technology
NEXT_PUBLIC_BUSINESS_ADDRESS=Nairobi CBD
NEXT_PUBLIC_BUSINESS_EMAIL=info@fixit-bluetechnology.co.ke
NEXT_PUBLIC_BUSINESS_PHONE=+254 707 454182
NEXT_PUBLIC_BUSINESS_TAGLINE=Your trusted repair & tech partner — fast, honest, professional.
"""

os.makedirs(ADMIN_DIR, exist_ok=True)

with open(ENV_FILE, "w", encoding="utf-8") as f:
    f.write(ENV_CONTENT)

try:
    os.chmod(ENV_FILE, 0o600)
    ok(".env permissions set to 600")
except Exception:
    pass

ok("admin/.env written", ENV_FILE)

# Print what was written for verification
print()
for line in ENV_CONTENT.strip().splitlines():
    if line and not line.startswith("#"):
        print(f"    {line}")


# ── Step 2: Check Node / npm ──────────────────────────────────────────────────

section("2. Checking Node.js / npm")

def run(cmd: list, cwd: str = None, capture: bool = True):
    result = subprocess.run(
        cmd, cwd=cwd,
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.PIPE if capture else None,
        text=True,
    )
    return result

node_check = run(["node", "--version"])
npm_check  = run(["npm",  "--version"])

if node_check.returncode != 0:
    fail("Node.js not found — install it on cPanel or use nvm")
    sys.exit(1)

ok("node", node_check.stdout.strip())
ok("npm",  npm_check.stdout.strip())


# ── Step 3: Install dependencies ─────────────────────────────────────────────

section("3. Installing npm dependencies")

pkg_json = os.path.join(ADMIN_DIR, "package.json")
if not os.path.exists(pkg_json):
    fail("package.json not found", ADMIN_DIR)
    sys.exit(1)

print("  Running: npm install --legacy-peer-deps")
result = run(["npm", "install", "--legacy-peer-deps"], cwd=ADMIN_DIR, capture=False)
if result.returncode != 0:
    fail("npm install failed")
    sys.exit(1)
ok("Dependencies installed")


# ── Step 4: Build Next.js ─────────────────────────────────────────────────────

section("4. Building Next.js (static export)")

print("  Running: npm run build  (this may take 1–2 minutes…)")
result = run(["npm", "run", "build"], cwd=ADMIN_DIR, capture=False)
if result.returncode != 0:
    fail("npm run build failed")
    sys.exit(1)
ok("Build complete — output in admin/out/")


# ── Step 5: Deploy to public_html ─────────────────────────────────────────────

section("5. Deploy built files")

OUT_DIR = os.path.join(ADMIN_DIR, "out")

# Detect cPanel home — try common paths
for candidate in [
    "/home2/fixitblu/public_html/admin",
    "/home/fixitblu/public_html/admin",
]:
    if os.path.exists(os.path.dirname(candidate)):
        DEPLOY_DIR = candidate
        break
else:
    DEPLOY_DIR = None

if not os.path.exists(OUT_DIR):
    fail("admin/out/ not found — build may have failed")
    sys.exit(1)

if DEPLOY_DIR:
    print(f"  Deploying to: {DEPLOY_DIR}")
    if os.path.exists(DEPLOY_DIR):
        shutil.rmtree(DEPLOY_DIR)
    shutil.copytree(OUT_DIR, DEPLOY_DIR)
    ok("Deployed to public_html/admin")
else:
    ok(
        "Skipping deploy — cPanel home not detected",
        f"Manually copy admin/out/ to your public_html/admin folder",
    )


# ── Done ──────────────────────────────────────────────────────────────────────

print(f"""
{'=' * 60}
  ✓  Admin env setup complete.

  API URL : https://api.fixit-bluetechnology.co.ke
  Business: Fixit Blue Technology
  Email   : info@fixit-bluetechnology.co.ke
  Phone   : +254 707 454182

  Next steps (if not auto-deployed):
    1. Copy admin/out/ to your cPanel public_html/admin folder
    2. Visit https://admin.fixit-bluetechnology.co.ke to verify
{'=' * 60}
""")
